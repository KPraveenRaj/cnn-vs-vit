PROBLEM = ("Vision Transformers now lead image-classification benchmarks, but those "
           "results rely on large-scale pre-training and compute, and most published "
           "CNN-versus-ViT comparisons vary many factors at once. This project "
           "fine-tunes a representative CNN and a representative ViT under a single "
           "controlled transfer-learning protocol and compares how the two families "
           "behave — beginning with their efficiency in low-data regimes and their "
           "robustness to input degradation. The aim is to characterise not just which "
           "model scores higher, but how and why each one behaves as it does.")


def _efficiency_table(doc, f, caption_no):
    headers = ["Model / regime", "10%", "25%", "50%", "100%"]
    rows = []
    for regime, tag in (("fullft", ""), ("linprobe", " (linear probe)")):
        for m, name in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16")):
            if f.top1(m, 100, regime=regime) is None and f.top1(m, 10, regime=regime) is None:
                continue
            e = f.efficiency_row(m, regime=regime)
            rows.append([name + tag, e[10], e[25], e[50], e[100]])
    if all(f.gap_at(x) is not None for x in (10, 100)):
        rows.append(["Gap (ViT − ResNet), full fine-tune",
                     f.gap_str(10), f.gap_str(25), f.gap_str(50), f.gap_str(100)])
    if not rows:
        rows = [["(pending)"] * 5]
    table(doc, headers, rows,
          f"Table {caption_no}: Frozen-test top-1 accuracy, mean ± standard deviation "
          f"over three seeds. Source: results/tables/master.csv.",
          widths=[2.3, 1.0, 1.0, 1.0, 1.0])


def _body(doc, f, final):
    d = f.dataset_facts()
    av = f.available()
    tno, fno = 1, 1

    h1(doc, "Abstract")
    para(doc, PROBLEM)
    para(doc, f"Two archetypes — ResNet-50 and ViT-B/16, both pre-trained on "
              f"ImageNet-1k only — were fine-tuned on Caltech-256 under one protocol "
              f"at nested per-class data fractions of 10, 25, 50 and 100 percent with "
              f"three seeds, and every checkpoint was put through a single evaluation "
              f"battery of {42} inference passes covering clean accuracy, corruption "
              f"robustness and spatial-frequency sensitivity. In total "
              f"{f.n_runs()} training runs were completed using {f.gpu_hours()} "
              f"GPU-hours on one RTX 4060 8 GB laptop GPU. Every figure and table in "
              f"this report is generated by script from a single results table.")

    h1(doc, "1. Introduction")
    h2(doc, "1.1 Motivation")
    para(doc, "Comparisons between convolutional networks and vision transformers are "
              "abundant, but most vary several factors simultaneously: pre-training "
              "corpus, augmentation recipe, optimiser, schedule length and compute "
              "budget often all differ between the two arms of a published comparison. "
              "An architecture conclusion drawn from such a comparison is not isolated "
              "from those confounds. This project takes the opposite approach — fix "
              "everything that can be fixed, declare what cannot, and then ask how the "
              "two families behave.")
    h2(doc, "1.2 Problem statement")
    para(doc, PROBLEM, italic=True)
    h2(doc, "1.3 Objectives")
    for b in ["Fine-tune one representative CNN and one representative ViT under a "
              "single controlled transfer-learning protocol.",
              "Measure data efficiency by varying only the quantity of training data, "
              "using nested per-class subsets so composition never changes.",
              "Measure robustness to input degradation under a corruption battery "
              "applied identically to both architectures.",
              "Characterise the spatial-frequency dependence of each family, and test "
              "whether it explains the robustness results.",
              "Report deployment cost, calibration and error overlap, so that the "
              "comparison is behavioural rather than a single accuracy number."]:
        bullet(doc, b)
    h2(doc, "1.4 Contributions")
    for b in ["A fully controlled, reproducible CNN-versus-ViT comparison in which the "
              "only declared per-model difference is a swept learning rate.",
              "Frequency-sensitivity curves measured as a function of the "
              "transfer-learning data fraction — the interaction, rather than the "
              "full-scale frequency difference already known from prior work.",
              "A public, script-generated result pipeline in which no reported number "
              "is entered by hand."]:
        bullet(doc, b)

    h1(doc, "2. Related Work")
    for title, text in [
        ("Transformers for vision",
         "Vaswani et al. (2017) introduced the transformer; Dosovitskiy et al. (2020) "
         "applied it to images as ViT, showing that with sufficient pre-training data a "
         "pure transformer matches or exceeds convolutional networks. Touvron et al. "
         "(2021) showed with DeiT that strong augmentation and distillation can remove "
         "the very-large-corpus requirement."),
        ("How the two families differ",
         "Park & Kim (ICLR 2022) analyse the two families in the frequency domain and "
         "argue that self-attention behaves as a low-pass filter while convolutions "
         "amplify high frequencies. Their analysis is at full scale and largely from "
         "scratch; the present work asks how that dependence behaves under transfer "
         "learning as the fine-tuning budget shrinks."),
        ("Robustness and frequency",
         "Hendrycks & Dietterich (2019) established the ImageNet-C corruption protocol "
         "used here for severity constants. Yin et al. (NeurIPS 2019) give the Fourier "
         "perspective on robustness, showing that models differ in which frequency bands "
         "a perturbation must occupy to hurt them — the band-limited-noise probe in this "
         "work follows that construction."),
        ("Scope of backbone comparisons",
         "Goldblum et al. (Battle of the Backbones, NeurIPS 2023) benchmark many "
         "backbones across many tasks. That work maximises breadth; this one maximises "
         "control, holding the protocol fixed over two archetypes to make the "
         "differences attributable.")]:
        h2(doc, title)
        para(doc, text)

    h1(doc, "3. Methodology")
    h2(doc, "3.1 What “controlled” means")
    para(doc, "Identical across both arms: pre-training source (ImageNet-1k only), data "
              "splits, augmentation pipeline, input resolution (224), schedule shape, "
              "optimiser family, seeds, and the entire evaluation path. The single "
              "declared exception is a per-model learning rate chosen by a documented "
              "three-point sweep, because forcing one learning rate on both "
              "architectures would cripple one of them and invalidate exactly the "
              "comparison being made. Per-model normalisation constants are taken from "
              "each backbone's own pre-training configuration — a second declared and "
              "symmetric difference.")
    para(doc, "One consequence is worth recording: timm's default ViT-B/16 weights are "
              "pre-trained on ImageNet-21k. Using them would have broken the single "
              "most important control in the study, so the ImageNet-1k-only "
              "'augreg_in1k' tag was pinned instead.")
    h2(doc, "3.2 Dataset and splits")
    para(doc, f"Caltech-256 is the primary dataset: {d['classes']} classes after "
              f"excluding the clutter class, {d['total']:,} images, split 70/10/20 "
              f"stratified per class into {d['train_f100']:,} training, {d['val']:,} "
              f"validation and {d['test']:,} frozen test images. The test split was "
              f"generated once, committed to version control, and has never influenced "
              f"any decision. Data fractions are per-class and strictly nested "
              f"(f10 ⊂ f25 ⊂ f50 ⊂ f100), with three independent seed nestings, so that "
              f"varying the fraction varies quantity alone and never composition.")
    figure(doc, f.figure("fraction_nesting.png"),
           f"Figure {fno}: Nested per-class data fractions.")
    fno += 1
    figure(doc, f.figure("class_distribution.png"),
           f"Figure {fno}: Caltech-256 is long-tailed, which is why macro-F1 and "
           f"worst-decile class accuracy are reported alongside top-1.")
    fno += 1
    h2(doc, "3.3 Models and training")
    rows = []
    for m, name in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16")):
        c = f.deployment_row(m)
        rows.append([name, c.get("timm_name", "—"),
                     f"{c.get('params_m', float('nan')):.1f}",
                     f"{c.get('gmacs', float('nan')):.2f}",
                     f"{c.get('feature_dim', float('nan')):.0f}",
                     f.lr_selected(m)])
    table(doc, ["Model", "timm tag", "Params (M)", "GMACs", "Feat. dim", "Swept LR"], rows,
          f"Table {tno}: The two architectures. Parameter counts and FLOPs measured "
          f"with torch's FLOP counter at 224×224.", widths=[1.0, 2.0, 0.85, 0.7, 0.7, 0.8])
    tno += 1
    para(doc, "Both models are trained with AdamW, a cosine schedule with linear warmup, "
              "an effective batch size of 64, mixed precision, and early stopping on "
              "validation top-1 with patience 5. On an 8 GB GPU the effective batch is "
              "reached through gradient accumulation; the micro-batch/accumulation split "
              "differs per model but the effective batch does not, so the optimisation "
              "protocol is identical.")
    h2(doc, "3.4 Augmentation")
    para(doc, "One modest pipeline for both models: RandomResizedCrop(224, scale "
              "0.5–1.0), horizontal flip, and light colour jitter. Heavy augmentation "
              "(mixup, CutMix, RandAugment) is deliberately excluded: it interacts "
              "strongly with architecture and would reintroduce exactly the confound "
              "this study removes.")
    figure(doc, f.figure("augmentation_samples.png"),
           f"Figure {fno}: The training augmentation pipeline.")
    fno += 1
    h2(doc, "3.5 Learning-rate sweeps")
    for m, name in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16")):
        grid = f.lr_grid(m)
        if grid:
            table(doc, ["Learning rate", "Best validation top-1", "Selected"],
                  [[lr, v, "yes" if sel else ""] for lr, v, sel in grid],
                  f"Table {tno}: Declared three-point learning-rate sweep for {name} "
                  f"(f100, seed 0, 8 epochs). Selection is on validation top-1 only.",
                  widths=[1.4, 1.6, 1.0])
            tno += 1
    para(doc, "The ViT grid sits one decade below the CNN grid. This is the substance of "
              "'declared per-model tuning': AdamW fine-tuning of a pre-trained ViT-B/16 "
              "has its optimum roughly a decade lower than a ResNet's, and reusing the "
              "CNN grid would have placed the transformer's optimum at or below the "
              "bottom edge of the search.")

    h1(doc, "4. Evaluation battery")
    para(doc, "Every checkpoint passes the same inference-only battery of 42 passes over "
              "the frozen test set: clean metrics; three corruption families at five "
              "ImageNet-C severities; ideal low-pass and high-pass sweeps over ten "
              "cutoff radii; and band-limited fixed-energy noise over six frequency "
              "annuli.")
    h2(doc, "4.1 Corruptions")
    para(doc, "Gaussian noise, Gaussian blur and JPEG compression at the five standard "
              "ImageNet-C severity constants, applied to the 224×224 crop in [0,1] "
              "before normalisation. Corrupted images are generated on the fly and never "
              "written to disk. The random draw for a given (corruption, severity, "
              "image) is derived from those three quantities alone, so both "
              "architectures are scored on byte-identical corrupted pixels and a rerun "
              "reproduces the numbers exactly.")
    figure(doc, f.figure("corruption_ladder.png"),
           f"Figure {fno}: The corruption battery at all five severities.")
    fno += 1
    h2(doc, "4.2 Frequency probes")
    para(doc, "Let x be one image channel and X its centred two-dimensional DFT. Writing "
              "the radial frequency of bin (i,j) as r = √(u² + v²) with u,v measured "
              "from DC, an ideal low-pass filter keeps r ≤ r_c and an ideal high-pass "
              "keeps r > r_c. The two masks are exact complements, so low-pass and "
              "high-pass at the same radius sum back to the original image; the "
              "implementation asserts this to within 4×10⁻⁷, which is the cheapest "
              "available proof that the filtering is correct. At the largest swept "
              "radius the low-pass mask covers every populated bin and the filter "
              "becomes the identity, giving the sweep a built-in correctness anchor.")
    para(doc, "For the second probe, Gaussian noise is band-limited to an annulus and "
              "then rescaled to a fixed spatial RMS. Rescaling after band-limiting is "
              "essential: annuli near Nyquist contain far more DFT bins than annuli near "
              "DC, so without renormalisation the curve would measure bin count rather "
              "than model sensitivity.")
    figure(doc, f.figure("fft_construction.png"),
           f"Figure {fno}: Construction of the frequency probes.")
    fno += 1
    figure(doc, f.figure("frequency_lowpass_ladder.png"),
           f"Figure {fno}: The ideal low-pass sweep. Ringing is the expected Gibbs "
           f"artefact of a brick-wall spectral cutoff.")
    fno += 1

    h1(doc, "5. Experimental setup")
    import json
    env_p = REPO_ROOT / "results" / "tables" / "environment.json"
    env = json.loads(env_p.read_text()) if env_p.exists() else {}
    libs, gpu = env.get("libs", {}), env.get("gpu", {})
    table(doc, ["Component", "Value"],
          [["GPU", f"{gpu.get('name', '—')} ({gpu.get('total_vram_gb', '—')} GB)"],
           ["NVIDIA driver", env.get("nvidia_driver", "—")],
           ["PyTorch", f"{libs.get('torch', '—')} (CUDA {libs.get('torch_cuda', '—')})"],
           ["timm", libs.get("timm", "—")],
           ["Determinism", "cuDNN deterministic, benchmark disabled, per-worker seeds"],
           ["Total compute", f"{f.gpu_hours()} GPU-hours"]],
          f"Table {tno}: Experimental environment, captured automatically into "
          f"results/tables/environment.json.", widths=[1.8, 4.0])
    tno += 1

    h1(doc, "6. Results")
    h2(doc, "6.1 Data efficiency")
    _efficiency_table(doc, f, tno); tno += 1
    figure(doc, f.figure("fig_data_efficiency.png"),
           f"Figure {fno}: Frozen-test top-1 against training fraction. Line is the "
           f"mean over three seeds, band is ±1 SD.")
    fno += 1
    if av["vit_fullft"]:
        g10, g100 = f.gap_at(10), f.gap_at(100)
        if g10 is not None and g100 is not None:
            para(doc, f"At the full training budget the two families differ by "
                      f"{f.gap_str(100)}; at a tenth of the data the difference is "
                      f"{f.gap_str(10)}. Because the two arms saw the same images, the "
                      f"same augmentation and the same schedule shape, and each was given "
                      f"its own swept learning rate, this difference is attributable to "
                      f"architecture and pre-training inductive bias rather than to "
                      f"tuning effort.")
    else:
        para(doc, "The ViT arm is still running; this section completes when it lands.",
             italic=True)
    h2(doc, "6.2 Corruption robustness")
    figure(doc, f.figure("fig_corruption.png"),
           f"Figure {fno}: Top-1 against corruption severity, f100.")
    fno += 1
    rows = [[n, f.top1_str(m, 100), f.corruption_drop(m)]
            for m, n in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16"))]
    table(doc, ["Model", "Clean top-1", "Mean relative drop"], rows,
          f"Table {tno}: Robustness cost, averaged over all fifteen corruption cells.",
          widths=[1.5, 1.5, 2.0])
    tno += 1
    h2(doc, "6.3 Frequency sensitivity")
    figure(doc, f.figure("fig_frequency.png"),
           f"Figure {fno}: Accuracy under ideal low-pass and high-pass filtering.")
    fno += 1
    figure(doc, f.figure("fig_band_noise.png"),
           f"Figure {fno}: Accuracy under fixed-energy noise as a function of the "
           f"frequency band the noise occupies.")
    fno += 1
    rows = [[n, f.freq_auc(m, "lp"), f.freq_auc(m, "hp"), f.band_weakness(m)]
            for m, n in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16"))]
    table(doc, ["Model", "Low-pass AUC", "High-pass AUC", "Most damaging band"], rows,
          f"Table {tno}: Frequency summary at f100.", widths=[1.3, 1.3, 1.3, 1.6])
    tno += 1
    h2(doc, "6.4 Frequency reliance × data fraction")
    figure(doc, f.figure("fig_frequency_interaction.png"),
           f"Figure {fno}: Low-pass accuracy-vs-cutoff curves, one panel per training "
           f"fraction. This interaction is the contribution of the study.")
    fno += 1
    h2(doc, "6.5 Error overlap")
    o = f.overlap_at(100)
    rows = ([["Cohen's κ on correctness", f"{o['kappa']:.3f}"],
             ["Both models wrong", f"{o['both_wrong']*100:.1f}%"],
             ["…giving the same wrong label", f"{o['same_wrong']*100:.1f}%"],
             ["Oracle top-1 (either right)", f"{o['oracle']*100:.2f}%"]]
            if o else [["(pending)", ""]])
    table(doc, ["Measure at f100", "Value"], rows,
          f"Table {tno}: Per-image agreement. κ corrects for the agreement two models "
          f"of this accuracy would reach by chance alone.", widths=[3.0, 1.5])
    tno += 1
    figure(doc, f.figure("fig_error_overlap.png"),
           f"Figure {fno}: Outcome split and chance-corrected agreement.")
    fno += 1
    h2(doc, "6.6 Calibration")
    figure(doc, f.figure("fig_calibration.png"),
           f"Figure {fno}: Reliability diagram and expected calibration error.")
    fno += 1
    h2(doc, "6.7 Deployment cost")
    figure(doc, f.figure("fig_deployment.png"), f"Figure {fno}: Deployment cost.")
    fno += 1
    return tno, fno


def build(final: bool):
    f = Facts()
    doc = new_doc()
    kind = "End-Semester Report" if final else "Mid-Semester Report"
    title_page(doc, TITLE.replace("\n", " "),
               f"EC789 Major Project – I · {kind}", META)
    tno, fno = _body(doc, f, final)

    h1(doc, "7. Discussion")
    para(doc, "The study was designed so that a null result would still be informative: "
              "in a controlled comparison, finding that two families behave the same on "
              "an axis is a finding, not a failure. The frequency axis was expected to "
              "separate them regardless, since the two backbones carry different "
              "pre-training inductive biases.")
    para(doc, "The value of the mechanism axis is that it converts a benchmark into an "
              "explanation. Corruption curves alone would say only that one family "
              "degrades faster. The frequency probes say which part of the input "
              "spectrum each family depends on, which is what makes the corruption "
              "ordering predictable rather than merely observed.")

    if final:
        h1(doc, "8. Cross-dataset confirmation: Food-101")
        if f.available()["food101"]:
            rows = [[n, f.top1_str(m, 25, dataset="food101"),
                     f.top1_str(m, 100, dataset="food101")]
                    for m, n in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16"))]
            table(doc, ["Model", "25% data", "100% data"], rows,
                  f"Table {tno}: Food-101 confirmation, single seed, full fine-tuning.",
                  widths=[1.6, 1.5, 1.5])
            tno += 1
        else:
            para(doc, "Food-101 was designated in the project plan as the first item to "
                      "cut under time pressure, and it was cut. The Caltech-256 result "
                      "stands on its own: two architectures, four data fractions, three "
                      "seeds, one protocol and a full evaluation battery. Recording the "
                      "cut as a declared scope decision is more honest than reporting a "
                      "rushed single-seed result.")

        h1(doc, "9. Limitations")
        for b in ["One CNN and one ViT are archetypes, not whole families; conclusions "
                  "are about these two representatives under this protocol.",
                  "Caltech-256 overlaps the ImageNet pre-training distribution. This "
                  "flatters both models, but symmetrically.",
                  "Ideal brick-wall filters ring. This is standard for the analysis and "
                  "is what makes the cutoff unambiguous, but it is a distortion of its "
                  "own and is reported as such.",
                  "Linear probes use no train-time augmentation — a declared difference "
                  "from the fine-tuning regime, applied identically to both models.",
                  "Three seeds bound run-to-run variance, not dataset variance."]:
            bullet(doc, b)

        h1(doc, "10. Conclusion and Phase-II plan")
    else:
        h1(doc, "8. Work remaining")
        av = f.available()
        for label, done in [("Caltech-256 full fine-tuning, both models",
                             av["resnet_fullft"] and av["vit_fullft"]),
                            ("Linear probes on cached features", av["probes"]),
                            ("Evaluation battery", av["battery"]),
                            ("Error overlap, calibration, deployment", av["overlap"]),
                            ("Food-101 cross-dataset confirmation", av["food101"])]:
            bullet(doc, f"{label} — {'complete' if done else 'remaining'}")
        h1(doc, "9. Conclusion and Phase-II plan")

    para(doc, "This phase delivers a controlled, reproducible comparison of a "
              "convolutional and a transformer backbone under transfer learning, on "
              "three axes — data efficiency, corruption robustness and spatial-frequency "
              "sensitivity — with supporting analyses of error overlap, calibration and "
              "deployment cost. The whole pipeline is public and script-generated.")
    para(doc, "Phase II (EC790) continues in the direction of generative and "
              "restoration-oriented vision transformers. The frequency machinery "
              "developed here transfers directly: image restoration is explicitly a "
              "frequency problem, and this phase has produced validated tooling for "
              "measuring what a model does band by band, along with the "
              "controlled-protocol discipline that makes such measurements comparable.")

    h1(doc, "References")
    for r in ["Vaswani, A. et al. (2017). Attention Is All You Need. NeurIPS.",
              "Dosovitskiy, A. et al. (2021). An Image Is Worth 16×16 Words: "
              "Transformers for Image Recognition at Scale. ICLR.",
              "Touvron, H. et al. (2021). Training Data-Efficient Image Transformers "
              "& Distillation through Attention. ICML.",
              "Park, N. & Kim, S. (2022). How Do Vision Transformers Work? ICLR.",
              "Yin, D. et al. (2019). A Fourier Perspective on Model Robustness in "
              "Computer Vision. NeurIPS.",
              "Hendrycks, D. & Dietterich, T. (2019). Benchmarking Neural Network "
              "Robustness to Common Corruptions and Perturbations. ICLR.",
              "Goldblum, M. et al. (2023). Battle of the Backbones. NeurIPS."]:
        bullet(doc, r)

    h1(doc, "Appendix A — Reproducibility")
    para(doc, "Repository: github.com/KPraveenRaj/cnn-vs-vit. Every run is keyed by a "
              "run ID of the form {model}_{dataset}_f{fraction}_s{seed}_{regime} and "
              "writes its own merged configuration, per-epoch log, metrics file and "
              "per-image prediction table. All tables and figures in this report are "
              "generated from results/tables/master.csv by scripts in src/analysis/; no "
              "number in this document was entered by hand.")
    save(doc, OUT / ("endsem_report.docx" if final else "midsem_report.docx"))


if __name__ == "__main__":
    build(final=False)
    build(final=True)
