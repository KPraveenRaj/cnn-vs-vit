def _efficiency_table(doc, f, caption_no):
    headers = ["Model / regime", "10%", "25%", "50%", "100%"]
    rows = []
    for regime, tag in (("fullft", ""), ("linprobe", " (linear probe)")):
        for m, name in (("resnet50", "ResNet-50"), ("vit_b16", "ViT-B/16")):
            if f.top1(m, 100, regime=regime) is None and f.top1(m, 10, regime=regime) is None:
                continue
            e = f.efficiency_row(m, regime=regime)
            rows.append([name + tag, e[10], e[25], e[50], e[100]])
    if all(f.gap_at(x) is not None for x in (10, 100)):
        rows.append(["Gap (ViT − ResNet), full fine-tune",
                     f.gap_str(10), f.gap_str(25), f.gap_str(50), f.gap_str(100)])
    if not rows:
        rows = [["(pending)"] * 5]
    table(doc, headers, rows,
          f"Table {caption_no}: Frozen-test top-1 accuracy, mean ± standard deviation "
          f"over three seeds. Source: results/tables/master.csv.",
          widths=[2.3, 1.0, 1.0, 1.0, 1.0])


